// Writes IMAGES.md, the final image mapping, from src/content/image-map.json,
// generated-images.json, live-images.json and the resolved table images.gen.json.
//   node scripts/images-manifest.mjs   (run after sync-images / a build)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (f) => JSON.parse(fs.readFileSync(path.join(root, f), "utf8"));
const live = read("src/content/live-images.json");
const map = read("src/content/image-map.json");
const dims = read("src/content/generated-images.json");
const table = read("src/content/images.gen.json");
const routes = read("src/content/routes.json");
const renames = fs.existsSync(path.join(root, "src/content/image-renames.json"))
  ? read("src/content/image-renames.json")
  : [];
const brand = read("src/content/brand.json");

const title = (key) => routes.find((r) => r.key === key)?.h1 ?? (key === "not-found" ? "404" : key);
const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const liveById = new Map(
  Object.values(live)
    .flat()
    .map((im) => [im.id, im]),
);
const describe = (ref) => {
  const [kind, id] = ref.split(":");
  if (kind === "gen") return `generated \`${id}\``;
  const im = liveById.get(id);
  return `LIVE \`${id}\`${im?.alt ? ` — “${cell(im.alt)}”` : ""}`;
};

const liveAll = Object.values(live).flat();
const liveOk = liveAll.filter((i) => i.ok).length;
const allRecords = [
  ...Object.values(table.slots),
  ...Object.values(table.heroes),
  ...Object.values(table.live).flat(),
];
const placeholders = allRecords.filter((r) => !r.ok);

// Where each generated image is used.
const uses = {};
for (const [k, ref] of Object.entries(map.heroes))
  if (ref.startsWith("gen:")) (uses[ref.slice(4)] ??= []).push(`hero: ${title(k)}`);
for (const [k, ref] of Object.entries(map.slots))
  if (ref.startsWith("gen:")) (uses[ref.slice(4)] ??= []).push(`slot \`${k}\``);

let md = `# Images

Generated by \`node scripts/images-manifest.mjs\`. Do not edit by hand: change
\`src/content/image-map.json\` and rebuild.

## Summary

| | Count |
|---|---|
| Generated images (\`src/assets/*.jpg\` → \`public/images/generated/\`) | ${Object.keys(dims).length} |
| LIVE images downloaded (the client's real work) | ${liveOk} / ${liveAll.length} |
| Heroes mapped | ${Object.keys(map.heroes).length} |
| Visual slots mapped (steps, cards, panels, hover reveals, slides) | ${Object.keys(map.slots).length} |
| Slots still showing a placeholder | ${placeholders.length}${placeholders.length ? ": " + placeholders.map((p) => `\`${p.id}\``).join(", ") : ""} |

## Pipeline

- \`npm run images:generated\` — \`scripts/process-generated-images.mjs\`: each \`src/assets/<name>.jpg\`
  (originals untouched, never imported by the app) → \`public/images/generated/<name>-{640,1024,1600,2400}.webp\`
  + \`<name>-1600.avif\`; \`public/og-image.jpg\` (1200×630) from \`home-hero\`.
- \`npm run images:download\` — \`scripts/download-live-images.mjs\`: live originals → \`public/images/<page>/<alt-slug>.webp\`
  (≤ 2000 px) + \`-{640,1024,1600}.webp\` variants (narrower than the original only) + one \`.avif\`; live og:images →
  \`public/images/og/<page>.jpg\`. File and folder names never contain a word ad blockers filter
  (\`scripts/neutral-paths.mjs\`, see “Renamed for ad blockers” below).
- \`npm run images:logos\` — \`scripts/process-logos.mjs\`: the client's logos \`src/assets/yb-logo-{color,white}.png\`
  (originals untouched): background made transparent, margins trimmed, 240 px tall →
  \`public/brand/yb-logo-color.png\` (${brand.color.w}×${brand.color.h}, light backgrounds) and
  \`public/brand/yb-logo-white.png\` (${brand.white.w}×${brand.white.h}, navy backgrounds).
- \`scripts/sync-images.mjs\` (runs on every dev/build) resolves \`image-map.json\` into \`src/content/images.gen.json\`.
- Rendering (\`src/components/media/Img.tsx\`): \`<picture>\` with AVIF + WebP \`srcset\`/\`sizes\`, \`width\`/\`height\`,
  verbatim alt (generated images are decorative, \`alt=""\`), \`loading="lazy"\` except heroes
  (\`fetchpriority="high"\`, AVIF preloaded in the page head). Generated images are cropped with an
  \`object-position\` focal point set per image where its subject actually sits.
- Each inner-page hero keeps the page's LIVE banner as a gold-framed diamond swatch, so the real photo and
  its alt stay on the page.

## Generated images

| Image | Source | Files | Focal point | Used for |
|---|---|---|---|---|
${Object.entries(dims)
  .map(
    ([n, d]) =>
      `| \`${n}\` | \`src/assets/${n}.jpg\` (${d.w}×${d.h}) | \`public/images/generated/${n}-{640,1024,1600,2400}.webp\`, \`${n}-1600.avif\` | ${map.focal[n] ?? map.focal.default} | ${(uses[n] ?? ["—"]).join("; ")} |`,
  )
  .join("\n")}

Also: \`public/og-image.jpg\` (1200×630, from \`home-hero\`) = og:image of every page without a live og:image
(home included). The FabricShader poster fallback is \`fabric\`.

## Heroes (also the mega-menu preview and chat card of each page)

| Page | Hero | Live banner swatch |
|---|---|---|
${Object.entries(map.heroes)
  .map(([k, ref]) => {
    const b = live[k]?.find((i) => i.id === `${k}-banner`);
    const swatch =
      k === "philosophie"
        ? "— (banner shown in the intro)"
        : k === "contact"
          ? `\`${b.id}\` — “${cell(b.alt)}” (strip under the address)`
          : b
            ? `\`${b.id}\` — “${cell(b.alt)}”`
            : "—";
    return `| ${cell(title(k))} | ${describe(ref)} | ${swatch} |`;
  })
  .join("\n")}

## Visual slots

| Slot | Image |
|---|---|
${Object.entries(map.slots)
  .map(([k, ref]) => `| \`${k}\` | ${describe(ref)} |`)
  .join("\n")}

## Renamed for ad blockers (old → new)

Ad blockers (uBlock / AdBlock: EasyList, Liste FR, AdGuard Français) drop requests whose path contains
words such as “publicite”, “pub”, “banner”, “affiche”. These ${renames.length} files (each with its
\`-<w>.webp\` / \`.avif\` variants) were renamed by \`scripts/rename-ad-paths.mjs\`; alts are unchanged
and page URLs are untouched.

| Old | New |
|---|---|
${renames.map((r) => `| \`${r.from}\` | \`${r.to}\` |`).join("\n")}

## LIVE images by page

`;

for (const [key, list] of Object.entries(live)) {
  if (!list.length) continue;
  md += `### ${cell(title(key))}\n\n| Slot | File | Size | Alt | Source | Status |\n|---|---|---|---|---|---|\n`;
  for (const im of list) {
    md += `| \`${im.id}\` | \`public${im.file}\` | ${im.w && im.h ? `${im.w}×${im.h}` : "—"} | ${cell(im.alt) || "—"} | ${im.original} | ${im.ok ? "downloaded" : "**missing**"} |\n`;
  }
  md += "\n";
}

fs.writeFileSync(path.join(root, "IMAGES.md"), md);
console.log(
  `IMAGES.md: ${Object.keys(dims).length} generated · LIVE ${liveOk}/${liveAll.length} · placeholders ${placeholders.length}`,
);
